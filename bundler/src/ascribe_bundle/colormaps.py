def list_colormaps() -> list[str]:
    """Available colormap names, in a stable order."""
    return list(COLORMAPS)


def gradient_stops(name: str, alpha_lo: float = 0.15, alpha_hi: float = 0.5) -> list:
    """Build a manifest `display.gradient` from a colormap.

    Alpha is 0 at and below `alpha_lo`, 1 at and above `alpha_hi`, and ramps linearly between --
    so `alpha_lo` sets how much of the low end is invisible (air, background, noise floor) and
    `alpha_hi` how quickly material becomes solid. Passing equal bounds gives a fully opaque
    gradient, which is mostly useful for flat two-dimensional previews.

    Returns `[[offset, "#rrggbbaa"], ...]`, the shape the manifest and viewer expect.
    """
    if name not in COLORMAPS:
        raise ValueError(
            f"unknown colormap {name!r}; available: {', '.join(list_colormaps())}"
        )
    if alpha_hi < alpha_lo:
        raise ValueError(
            f"alpha_lo ({alpha_lo}) must not exceed alpha_hi ({alpha_hi})"
        )

    def alpha_at(offset: float) -> float:
        if alpha_hi <= alpha_lo:
            return 1.0
        return min(1.0, max(0.0, (offset - alpha_lo) / (alpha_hi - alpha_lo)))

    def encode(r: float, g: float, b: float, a: float) -> str:
        return "#" + "".join(
            f"{int(round(min(1.0, max(0.0, c)) * 255)):02x}" for c in (r, g, b, a)
        )

    table = COLORMAPS[name]
    stops: list[list] = []

    # Pad the transparent low end with the colormap's own first colour.
    _, r0, g0, b0 = table[0]
    if alpha_lo > 0.0:
        stops.append([0.0, encode(r0, g0, b0, 0.0)])

    for offset, r, g, b in table:
        if offset <= alpha_lo and stops:
            # Inside the transparent pad: keep the low colour so nothing drags toward black.
            r, g, b = r0, g0, b0
        stops.append([round(offset, 4), encode(r, g, b, alpha_at(offset))])

    # Make sure the ramp's endpoints are represented exactly, so the fade starts and finishes
    # where the caller asked rather than wherever the sampled stops happen to fall.
    for edge in (alpha_lo, alpha_hi):
        if 0.0 < edge < 1.0 and not any(abs(s[0] - edge) < 1e-6 for s in stops):
            colour = _sample(table, edge)
            if edge <= alpha_lo:
                colour = (r0, g0, b0)
            stops.append([round(edge, 4), encode(*colour, alpha_at(edge))])

    stops.sort(key=lambda s: s[0])
    return stops


def _sample(table: list[tuple[float, float, float, float]], offset: float):
    """Linearly interpolate a colormap table at `offset`."""
    if offset <= table[0][0]:
        return table[0][1:]
    for (o0, r0, g0, b0), (o1, r1, g1, b1) in zip(table, table[1:]):
        if offset <= o1:
            t = 0.0 if o1 == o0 else (offset - o0) / (o1 - o0)
            return (r0 + (r1 - r0) * t, g0 + (g1 - g0) * t, b0 + (b1 - b0) * t)
    return table[-1][1:]
